export const getCurrentLanguage = (): Language => {
  const stored = localStorage.getItem('civx_language') as Language;
  return stored && DICTIONARY[stored] ? stored : 'en';
};

export const setCurrentLanguage = (lang: Language): void => {
  localStorage.setItem('civx_language', lang);
  window.dispatchEvent(new Event('civx_lang_change'));
};

export const t = (key: string, overrideLang?: Language): string => {
  const lang = overrideLang || getCurrentLanguage();
  return DICTIONARY[lang]?.[key] || DICTIONARY['en']?.[key] || key;
};
